"""
Subprocess Execution Engine
Executes code generated by the Coder node in a controlled sandbox.
Captures stdout, stderr, exit code, and produces structured ExecutionResult.
"""

import sys
import os
import subprocess
import tempfile
import time
from pathlib import Path

from core.config import config
from core.schemas import ExecutionResult


def truncate_output(text: str, max_chars: int = 2500) -> str:
    """Truncates large outputs while preserving head and tail."""
    if not text or len(text) <= max_chars:
        return text or ""
    half = max_chars // 2
    return (
        text[:half]
        + f"\n... [truncated {len(text) - max_chars} characters for token savings] ...\n"
        + text[-half:]
    )


class CodeExecutor:
    def __init__(self, working_dir: str = None, timeout: float = None):
        self.working_dir = working_dir or config.workspace_root
        self.timeout = timeout or config.execution_timeout
        Path(self.working_dir).mkdir(parents=True, exist_ok=True)

    def execute_python(self, code_str: str, attempt: int = 1) -> ExecutionResult:
        """
        Executes a Python code string in a subprocess.
        Returns a fully structured ExecutionResult with error classification.
        """
        temp_file = None
        start_time = time.time()
        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                suffix=".py",
                dir=self.working_dir,
                delete=False,
                encoding="utf-8",
            ) as f:
                f.write(code_str)
                temp_file = f.name

            cmd = [sys.executable, temp_file]
            env = os.environ.copy()
            existing_pp = env.get("PYTHONPATH", "")
            env["PYTHONPATH"] = (
                f"{self.working_dir}:{existing_pp}" if existing_pp else self.working_dir
            )

            proc = subprocess.run(
                cmd,
                cwd=self.working_dir,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                timeout=self.timeout,
                env=env,
            )

            duration = time.time() - start_time
            stdout = truncate_output(proc.stdout, config.max_output_chars)
            stderr = truncate_output(proc.stderr, config.max_output_chars)

            return ExecutionResult.from_process(
                stdout=stdout,
                stderr=stderr,
                exit_code=proc.returncode,
                duration=duration,
                code=code_str,
                file=os.path.basename(temp_file) if temp_file else "",
                attempt=attempt,
            )

        except subprocess.TimeoutExpired:
            duration = time.time() - start_time
            return ExecutionResult.from_process(
                stdout="",
                stderr=f"Execution timed out after {self.timeout} seconds.",
                exit_code=-1,
                duration=duration,
                code=code_str,
                file=os.path.basename(temp_file) if temp_file else "",
                attempt=attempt,
            )
        except Exception as e:
            duration = time.time() - start_time
            return ExecutionResult.from_process(
                stdout="",
                stderr=f"Executor failed to run code: {str(e)}",
                exit_code=-1,
                duration=duration,
                code=code_str,
                file=os.path.basename(temp_file) if temp_file else "",
                attempt=attempt,
            )
        finally:
            if temp_file and os.path.exists(temp_file):
                try:
                    os.remove(temp_file)
                except OSError:
                    pass
